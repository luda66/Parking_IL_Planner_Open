import argparse
import os

import matplotlib
import numpy as np

matplotlib.use('Agg')
import matplotlib.pyplot as plt
import torch
from PIL import Image

from parking_il_planner.config.model import MODEL_CONFIG
from parking_il_planner.data.dataset import ParkingDataset
from parking_il_planner.models.planner_model import build_apa_model

ACTION_NAMES = ['S0', 'S+', 'S-', 'L+', 'L-', 'R+', 'R-']
EVAL_DIR = 'artifacts/evaluation'
FRAMES_DIR = os.path.join(EVAL_DIR, 'parking_frames')
DEVICE = 'cuda' if torch.cuda.is_available() else 'cpu'

PRESET_SCENES = [
    {'name': 'scene1_long_51f', 'start': 8703,  'desc': 'Longest trajectory (51 frames, 2.43m start)'},
    {'name': 'scene2_long_51f', 'start': 20344, 'desc': 'Another long one (51 frames, 2.53m start)'},
    {'name': 'scene3_diverse_32f', 'start': 16000, 'desc': 'Most diverse actions (6 types, 32 frames)'},
    {'name': 'scene4_straight_48f', 'start': 0,    'desc': 'Mostly straight approach (48 frames, 2.38m)'},
    {'name': 'scene5_short_25f', 'start': 8622,  'desc': 'Short close-range (25 frames, 0.43m start)'},
]

def select_random_trajectories(dataset, n, seed=42):
    """随机选择n条轨迹"""
    np.random.seed(seed)
    
    states = dataset.states
    actions = dataset.actions
    targets = states[:, 3:6]
    
    # Find all trajectories
    trajectories = []
    curr_start = 0
    curr_target = targets[0]
    tol = 0.01
    
    for i in range(1, len(states)):
        if not np.allclose(targets[i], curr_target, atol=tol):
            length = i - curr_start
            if length >= 10:
                start_dist = np.sqrt(
                    (states[curr_start][0] - curr_target[0])**2 +
                    (states[curr_start][1] - curr_target[1])**2
                )
                end_dist = np.sqrt(
                    (states[i-1][0] - curr_target[0])**2 +
                    (states[i-1][1] - curr_target[1])**2
                )
                traj_actions = actions[curr_start:i]
                unique = len(set(traj_actions))
                dominant = ACTION_NAMES[np.bincount(traj_actions).argmax()]
                trajectories.append({
                    'start': curr_start, 'len': length,
                    'start_dist': start_dist, 'end_dist': end_dist,
                    'unique_actions': unique, 'dominant': dominant
                })
            curr_start = i
            curr_target = targets[i]
    
    if n > len(trajectories):
        n = len(trajectories)
    
    indices = np.random.choice(len(trajectories), n, replace=False)
    selected = [trajectories[i] for i in indices]
    
    return selected

def run_inference(scene, si, total, model, dataset):
    """对单个场景运行推理并生成GIF和帧"""
    print(f"\n{'='*50}")
    print(f"Scene {si}/{total}: {scene['name']}")
    print(f"  {scene.get('desc', '')}")

    target = dataset.states[scene['start']][3:6]
    tol = 0.01
    traj_len = 1
    for i in range(scene['start'] + 1, len(dataset.states)):
        if not np.allclose(dataset.states[i][3:6], target, atol=tol):
            break
        traj_len += 1

    print(f"  Actual length: {traj_len} frames")

    frames_dir = os.path.join(FRAMES_DIR, scene['name'])
    os.makedirs(frames_dir, exist_ok=True)

    gif_images = []
    correct_count = 0

    # === CORE INFERENCE LOOP ===
    # This is NOT closed-loop. We do NOT change the vehicle state.
    # We simply classify each pre-existing frame independently.
    for i in range(traj_len):
        idx = scene['start'] + i  # Index into the pre-existing dataset
        
        # Load the pre-rendered occupancy grid (NOT re-rendered!)
        img = dataset.images[idx].astype(np.float32) / 255.0
        s = dataset.states[idx]       # Pre-existing state
        a = int(dataset.actions[idx]) # Pre-existing ground-truth action
        
        # Calculate distance to target (for information only)
        dist = np.sqrt((s[0]-s[3])**2 + (s[1]-s[4])**2)

        # Single-frame classification (no state update!)
        img_t = torch.tensor(img[np.newaxis, ...]).to(DEVICE)
        with torch.no_grad():
            logits = model(img_t)              # Raw scores (B, 7)
            probs = torch.softmax(logits, -1)  # Probability distribution
            preds = torch.argmax(logits, -1)   # Predicted action index

        pa = preds.item()          # Model's predicted action (0-6)
        pr = probs[0].cpu().numpy() # Full probability distribution
        ok = a == pa               # Compare against pre-existing label
        conf = pr[pa] * 100        # Confidence of prediction
        if ok:
            correct_count += 1

        fig, ax = plt.subplots(1, 1, figsize=(5, 5))
        ax.imshow(img.transpose(1, 2, 0))
        for sp in ax.spines.values():
            sp.set_edgecolor('#00CC00' if ok else '#FF0000')
            sp.set_linewidth(4)

        status = "OK" if ok else "WRONG"
        title = (
            f'{scene["name"]} - Frame {i+1}/{traj_len}\n'
            f'GT: {ACTION_NAMES[a]}  |  Pred: {ACTION_NAMES[pa]} ({conf:.0f}%)  |  {status}\n'
            f'Dist: {dist:.2f}m'
        )
        ax.set_title(title, fontsize=10, color='#00AA00' if ok else '#DD0000', fontweight='bold')
        ax.axis('off')
        plt.tight_layout()

        frame_path = os.path.join(frames_dir, f'frame_{i+1:03d}.png')
        plt.savefig(frame_path, dpi=80, bbox_inches='tight')
        plt.close(fig)

        pil_img = Image.open(frame_path).resize((400, 400), Image.LANCZOS)
        gif_images.append(pil_img)

        if (i + 1) % 10 == 0:
            print(f"  Processed {i+1}/{traj_len}...")

    acc = correct_count / traj_len * 100

    gif_path = os.path.join(EVAL_DIR, f'{scene["name"]}.gif')
    gif_images[0].save(
        gif_path, save_all=True, append_images=gif_images[1:],
        duration=400, loop=0, optimize=True
    )
    print(f"  Accuracy: {correct_count}/{traj_len} ({acc:.0f}%)")
    print(f"  GIF: {gif_path}")
    print(f"  Frames: {frames_dir}/")

def main():
    global EVAL_DIR, FRAMES_DIR

    parser = argparse.ArgumentParser(description='APA Model Inference')
    parser.add_argument('--scene', type=int, default=None, help='Run specific preset scene (1-5)')
    parser.add_argument('--random', type=int, default=0, help='Randomly select N trajectories')
    parser.add_argument('--seed', type=int, default=42, help='Random seed (default: 42)')
    parser.add_argument('--data-dir', default='data/generated', help='Generated dataset directory')
    parser.add_argument('--checkpoint', default='checkpoints/best.pt', help='Model checkpoint')
    parser.add_argument('--output-dir', default='artifacts/evaluation/open_loop', help='Output directory')
    args = parser.parse_args()

    EVAL_DIR = args.output_dir
    FRAMES_DIR = os.path.join(EVAL_DIR, 'parking_frames')

    os.makedirs(EVAL_DIR, exist_ok=True)
    os.makedirs(FRAMES_DIR, exist_ok=True)

    print("=" * 70)
    print("APA Model Inference")
    print("=" * 70)

    print("\nLoading model...")
    if not os.path.isfile(args.checkpoint):
        parser.error(f"checkpoint not found: {args.checkpoint}; train a model or provide --checkpoint")
    cp = torch.load(args.checkpoint, map_location=DEVICE, weights_only=True)
    model = build_apa_model(MODEL_CONFIG, device=DEVICE)
    model.load_state_dict(cp['model_state_dict'])
    model.eval()

    print("Loading data...")
    dataset = ParkingDataset(args.data_dir, load_images=True)
    print(f"  Dataset: {len(dataset)} samples")

    # Determine which scenes to run
    if args.random > 0:
        trajectories = select_random_trajectories(dataset, args.random, args.seed)
        scenes = []
        for i, t in enumerate(trajectories, 1):
            scenes.append({
                'name': f'random{i}_{t["len"]}f_seed{args.seed}',
                'start': t['start'],
                'desc': f'Random trajectory (start={t["start"]}, {t["len"]} frames, {t["start_dist"]:.2f}m start, dominant={t["dominant"]})'
            })
        print(f"\nRandomly selected {len(scenes)} trajectories (seed={args.seed}):")
        for i, s in enumerate(scenes, 1):
            print(f"  {i}. {s['name']}: {s['desc']}")
    elif args.scene is not None:
        scenes = [PRESET_SCENES[args.scene - 1]]
    else:
        scenes = PRESET_SCENES

    # Run inference
    for si, scene in enumerate(scenes, 1):
        run_inference(scene, si, len(scenes), model, dataset)

    print("\n" + "=" * 70)
    print("ALL DONE")
    print("=" * 70)
    print("\nOutput:")
    print(f"  GIFs: {EVAL_DIR}/")
    print(f"  Frames: {FRAMES_DIR}/")

if __name__ == '__main__':
    main()
